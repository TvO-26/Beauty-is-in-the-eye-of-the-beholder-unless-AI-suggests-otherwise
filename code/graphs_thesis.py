INK, LIGHT, WARM, GOLD, GREY = "#1b4965", "#5fa8d3", "#c26b3e", "#e8b04b", "#9aa5ad"
CCOL = {"ai": INK, "human": WARM, "none": GREY}
CLAB = {"ai": "AI", "human": "Human", "none": "Control"}


SRC = "JASP_trials_long.csv"
trials = [r for r in csv.DictReader(open(SRC))
          if r["exclude"] == "" and r["complete_ratings"] == "yes"
          and r["has_rating"] == "yes"]


ratings_by_condition = defaultdict(list)
for r in trials:
    condition = r['condition']
    rating = int(float(r['rating']))
    ratings_by_condition[condition].append(rating)

# activate counter
rating_counts_by_condition = {cond: Counter(ratings) for cond, ratings in ratings_by_condition.items()}

fig, ax = plt.subplots(figsize=(12, 6))
rating_scale = np.arange(1, 11)
width = 0.25
sorted_conditions = sorted(CCOL.keys(), key=lambda k: CLAB[k])

# bar per condition
for i, cond_key in enumerate(sorted_conditions):
    counts = [rating_counts_by_condition[cond_key].get(r, 0) for r in rating_scale]
    x = rating_scale + (i - (len(sorted_conditions) - 1) / 2) * width

    ax.bar(x, counts, width, label=CLAB[cond_key], color=CCOL[cond_key], edgecolor='white', linewidth=0.5)

ax.set_xlabel("Rating (1-10)", fontsize=10)
ax.set_ylabel("Number of Ratings", fontsize=10)
ax.set_title("Distribution of Individual Ratings by Condition", loc='left', fontsize=12, pad=10)
ax.set_xticks(rating_scale)
ax.tick_params(axis="x", labelsize=9)
ax.tick_params(axis="y", labelsize=9)


ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)
ax.spines["left"].set_color("#cccccc")
ax.spines["bottom"].set_color("#cccccc")
ax.grid(axis="y", color="#e6e6e6", lw=0.6, zorder=0)
ax.set_axisbelow(True)

ax.legend(fontsize=8, frameon=False, loc="upper left")

fig.tight_layout()
