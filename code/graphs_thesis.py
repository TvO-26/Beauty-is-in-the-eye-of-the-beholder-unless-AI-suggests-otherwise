# Function to load and resize painting images
def get_painting_image(painting_id, size=(30, 30)):
    try:
        # match filename convention
        cleaned_painting_id = painting_id.replace(' ', '-')
        # Adding 'Copy of '
        img_name = f"Copy of {cleaned_painting_id}.png"
        img_path = os.path.join(IMG_FOLDER_PATH, img_name) # Use os.path.join for robust path construction
        img = Image.open(img_path)
        img.thumbnail(size, Image.LANCZOS)
        return OffsetImage(img, zoom=1)
    except FileNotFoundError:
        print(f"Warning: Image file not found for {painting_id} (expected: {img_path}). Skipping image.")
        return None
    except Exception as e:
        print(f"Error loading image for {painting_id}: {e}")
        return None

rows = [r for r in csv.DictReader(open(SRC))
        if r["exclude"] == "" and r["complete_ratings"] == "yes"
        and r["has_rating"] == "yes"]

by_painting = defaultdict(list)
quadrant = {}
for r in rows:
    by_painting[r["painting"]].append(float(r["rating"]))
    quadrant[r["painting"]] = (r["semantic_level"], r["perceptual_level"])

QCOL = {("high", "high"): "#1b4965", ("low", "high"): "#5fa8d3",
        ("high", "low"): "#c26b3e", ("low", "low"): "#e8b04b"}
QLAB = {("high", "high"): "High semantic, high perceptual",
        ("low", "high"): "Low semantic, high perceptual",
        ("high", "low"): "High semantic, low perceptual",
        ("low", "low"): "Low semantic, low perceptual"}

stats = []
for pid, vals in by_painting.items():
    vals = sorted(vals)
    n = len(vals)
    q1 = st.quantiles(vals, n=4)[0]
    q3 = st.quantiles(vals, n=4)[2]
    stats.append(dict(painting=pid, n=n, mean=st.mean(vals), median=st.median(vals),
                      q1=q1, q3=q3, lo=vals[0], hi=vals[-1],
                      quad=quadrant[pid]))


quadrant_order_map = {
    ("high", "high"): 0,
    ("low", "high"): 1,
    ("high", "low"): 2,
    ("low", "low"): 3
}

#order by quadrant
stats.sort(key=lambda d: (quadrant_order_map[d["quad"]], d["mean"]))

grand = st.mean(float(r["rating"]) for r in rows)

fig, ax = plt.subplots(figsize=(7.5, 8.4))
ax.axvline(grand, color="#999999", lw=1, ls="--", zorder=0)
ax.text(grand, len(stats) - 0.2, f"  grand mean {grand:.2f}",
        color="#666666", fontsize=8, va="bottom")

# Store painting IDs to be used as labels
painting_labels = [d["painting"] for d in stats]

for i, d in enumerate(stats):
    col = QCOL[d["quad"]]
    ax.plot([d["lo"], d["hi"]], [i, i], color=col, lw=0.9, alpha=0.45,
            solid_capstyle="round", zorder=1)
    ax.plot([d["q1"], d["q3"]], [i, i], color=col, lw=4.2, alpha=0.75,
            solid_capstyle="round", zorder=2)
    ax.plot([d["median"]], [i], marker="|", ms=11, mew=1.8,
            color="white", zorder=4)
    ax.plot([d["mean"]], [i], marker="o", ms=6.0, color=col,
            mec="white", mew=1.1, zorder=5)

    # Add painting ID text label
    ax.text(-2.3, i, d["painting"], ha="left", va="center", fontsize=8, color="#333333", zorder=6)

    # Align painting image
    img_offset = get_painting_image(d["painting"])
    if img_offset:
        ab = AnnotationBbox(img_offset, (-2.8, i),
                            xycoords='data',
                            boxcoords="offset points",
                            box_alignment=(1., 0.5),
                            frameon=False,
                            zorder=7)
        ax.add_artist(ab)

ax.set_yticks(range(len(stats)))
ax.set_yticklabels([])
ax.set_ylim(-0.8, len(stats) - 0.2)
ax.set_xlim(-3.0, 10.4)
ax.set_xticks(range(0, 11))
ax.set_xlabel("Aesthetic rating", fontsize=10)
ax.tick_params(axis="x", labelsize=9)
for side in ("top", "right", "left"):
    ax.spines[side].set_visible(False)
ax.grid(axis="x", color="#e6e6e6", lw=0.6, zorder=0)
ax.set_axisbelow(True)

handles = [Line2D([], [], color=QCOL[q], lw=4.2, alpha=0.75, label=QLAB[q])
           for q in [("high", "high"), ("low", "high"),
                     ("high", "low"), ("low", "low")]]
handles += [Line2D([], [], color="#444444", marker="o", ms=6, ls="",
                   mec="white", label="Mean"),
            Line2D([], [], color="#444444", marker="|", ms=11, mew=1.8, ls="",
                   label="Median")]
ax.legend(handles=handles, fontsize=8, frameon=False, ncol=2,
          loc="upper center", bbox_to_anchor=(0.5, -0.06))

fig.tight_layout()
for ext in ("png", "pdf"):
    fig.savefig(f"{OUT}/Figure_ratings_by_painting.{ext}", dpi=300,
                bbox_inches="tight")

print(f"{len(stats)} paintings, {len(rows)} ratings, grand mean {grand:.2f}")
print(f"painting means range {stats[0]['mean']:.2f} ({stats[0]['painting']}) "
      f"to {stats[-1]['mean']:.2f} ({stats[-1]['painting']})")
print(f"between-painting SD of means "
      f"{st.stdev(d['mean'] for d in stats):.2f}")

